// Turn the owner's invoice workbook into the template the app fills.
//
//   node scripts/build-invoice-template.mjs "C:/…/MRC NEW.xlsx"
//
// The owner's file is a real, filled-in invoice: it carries a customer's name,
// address and items as sample content. Those must not ship inside the app — a
// value that is merely overwritten in sheet1.xml still sits in sharedStrings.xml
// and travels inside every invoice generated from it. So this script blanks the
// sample strings and numbers, keeps everything else byte-for-byte (logo, the
// KCRP SOLUTION text box, the gold bar, styles, the item table), and writes the
// result as base64 into lib/invoices/template-data.ts.
//
// Re-run it whenever the owner sends a new design.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import JSZip from "jszip";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/build-invoice-template.mjs <invoice.xlsx>");
  process.exit(2);
}
const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const zip = await JSZip.loadAsync(readFileSync(src));
const sheetPath = "xl/worksheets/sheet1.xml";
const stringsPath = "xl/sharedStrings.xml";
let sheet = await zip.file(sheetPath).async("string");
let strings = await zip.file(stringsPath).async("string");

// The cells the app fills. Their sample values are removed here; the app
// writes inline values into the same cells, keeping each cell's style.
const FILLED = ["B2", "B3", "B5", "B6", "C5", "B9", "B10", "B11", "B12", "C9", "C10", "C11", "C12", "C13", "C14"];

const referenced = new Set();
for (const ref of FILLED) {
  const re = new RegExp(`<c r="${ref}"([^>]*?)(?:/>|>([\\s\\S]*?)</c>)`);
  const m = sheet.match(re);
  if (!m) continue;
  const attrs = m[1];
  const inner = m[2] ?? "";
  if (/t="s"/.test(attrs)) {
    const v = inner.match(/<v>(\d+)<\/v>/);
    if (v) referenced.add(Number(v[1]));
  }
  // Keep the style, drop the value and the type.
  const style = attrs.match(/s="\d+"/)?.[0] ?? "";
  sheet = sheet.replace(m[0], `<c r="${ref}" ${style}/>`);
}

// Blank every shared string that only the filled cells used.
let index = -1;
strings = strings.replace(/<si>[\s\S]*?<\/si>/g, (si) => {
  index += 1;
  return referenced.has(index) ? "<si><t></t></si>" : si;
});

zip.file(sheetPath, sheet);
zip.file(stringsPath, strings);
const out = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });

writeFileSync(
  resolve(REPO, "lib/invoices/template-data.ts"),
  "// GENERATED by scripts/build-invoice-template.mjs — do not edit by hand.\n" +
  "// The owner's invoice workbook with its sample customer data removed.\n" +
  `export const INVOICE_TEMPLATE_BASE64 =\n  "${out.toString("base64")}";\n`,
);
console.log(`template: ${out.length} bytes; blanked ${referenced.size} sample strings: ${[...referenced].join(", ")}`);
